def make_a3_sample() -> Dict:
    scene = random.choice(_A3_SCENES)
    chosen = random.choice(scene["chosen"])
    rejected = random.choice(scene["rejected"])
    return {
        "prompt": build_prompt(scene["turns"], scene["user"]),
        "chosen": chosen,
        "rejected": rejected,
        "tag": "no_apology_chain",
    }


def validate_a3(s: Dict) -> bool:
    chosen, rejected = s["chosen"], s["rejected"]
    if not (validate_common(chosen) and validate_common(rejected)):
        return False
    if chosen == rejected:
        return False
    if any(w in chosen for w in APOLOGY_WORDS):
        return False
    if not any(w in rejected for w in APOLOGY_WORDS):
        return False
    return True


