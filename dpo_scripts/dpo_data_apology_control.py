def collect_samples(target: int, builder, validator, results: List, seen: set) -> int:
    count = 0
    attempts = 0
    while count < target and attempts < target * 50:
        attempts += 1
        sample = builder()
        if not validator(sample):
            continue
        key = sample_key(sample)
        if key in seen:
            continue
        seen.add(key)
        results.append(sample)
        count += 1
    return count


