MIN_LEN = 20
MAX_LEN = 40

_ASTRAL_RE = re.compile(r"[\U00010000-\U0010ffff]")


def _bare_len(text: str) -> int:
    return len(_ASTRAL_RE.sub("", text).strip())


def _check_len(text: str) -> bool:
    return MIN_LEN <= _bare_len(text) <= MAX_LEN


def _content_key(scene: Dict, chosen: str, rejected: str) -> str:
    """内容级去重 key，不含随机 system prompt，避免相同语义重复写入。"""
    turns_str = json.dumps(scene["turns"], ensure_ascii=False, sort_keys=True)
    return f"{scene['tag']}||{turns_str}||{scene['user']}||{chosen}||{rejected}"


def _build_samples(scenes: List[Dict], quota: int) -> List[Dict]:
    """
    通用构建函数：枚举所有(场景×chosen×rejected)组合 → 随机打散 → 按 quota 采样。
    使用内容级 key 去重，确保各场景均匀覆盖。
    scene 的 time_ctx 字段控制 system prompt 时间，避免"深夜"与"午休"等场景冲突。
    """
    # 枚举全量合法组合
    combos: List[Tuple[Dict, str, str]] = []
    for scene in scenes:
        for chosen in scene["chosen_pool"]:
            if not _check_len(chosen):
                continue
            for rejected in scene["rejected_pool"]:
                if not validate_text(rejected):
                    continue
                combos.append((scene, chosen, rejected))

    random.shuffle(combos)

    samples: List[Dict] = []
    seen: set = set()
    for scene, chosen, rejected in combos:
        if len(samples) >= quota:
            break
        key = _content_key(scene, chosen, rejected)
        if key in seen:
            continue

        # 根据 time_ctx 生成与场景语境匹配的 system prompt
        time_ctx = scene.get("time_ctx")
        if time_ctx and time_ctx in _TIME_CTX_MAP:
            days, periods = _TIME_CTX_MAP[time_ctx]
            sys_content = sample_sys_prompt_with_time(
                random.choice(days), random.choice(periods)
            )
        else:
            sys_content = sample_sys_prompt()

        sample = {
            "prompt": build_prompt(
                scene["turns"], scene["user"], sys_content=sys_content
            ),
            "chosen": chosen,
            "rejected": rejected,
            "tag": scene["tag"],
        }
        samples.append(sample)
        seen.add(key)

    return samples


