def validate_s2(s: Dict) -> bool:
    chosen, rejected = s["chosen"], s["rejected"]
    if not validate_chosen(chosen):
        return False
    if not validate_rejected(rejected):
        return False
    if chosen == rejected:
        return False
    return True


